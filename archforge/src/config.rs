/// P2P swarm configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SwarmConfig {
    /// Enable P2P networking
    #[serde(default)]
    pub enabled: bool,

    /// Listen on these addresses
    #[serde(default = "default_listen_addrs")]
    pub listen_addrs: Vec<String>,

    /// Enable mDNS peer discovery
    #[serde(default = "default_mdns")]
    pub mdns: bool,

    /// Enable telemetry sharing
    #[serde(default = "default_telemetry")]
    pub telemetry: bool,

    /// Database path
    #[serde(default = "default_db_path")]
    pub db_path: PathBuf,
}

impl Default for SwarmConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            listen_addrs: default_listen_addrs(),
            mdns: default_mdns(),
            telemetry: default_telemetry(),
            db_path: default_db_path(),
        }
    }
}

fn default_listen_addrs() -> Vec<String> {
    vec!["/ip4/0.0.0.0/tcp/0".to_string()]
}

fn default_mdns() -> bool {
    true
}

fn default_telemetry() -> bool {
    false
}

fn default_db_path() -> PathBuf {
    let mut dir = dirs::data_dir().unwrap_or_else(|| PathBuf::from("/var/lib"));
    dir.push("archforge");
    dir.push("swarm.db");
    dir
}

/// Deployment configuration
